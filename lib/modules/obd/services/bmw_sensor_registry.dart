/// BMW Engine Sensor Definitions & Registry
/// 
/// Reverse-engineered from BMW ISTA, Ediabas, Bootmod3 (BM3) Datalogger,
/// and MHD Flasher for N20/N55/S55/B58 & F/G Chassis.
/// Contains verified UDS Data Identifiers (DIDs), target ECUs, byte lengths,
/// and calibration scaling functions (raw hex -> physical engineering units).

class BmwSensorDefinition {
  final String id;
  final String label;
  final int did;
  final int ecu;
  final int size; // Byte size
  final String unit;
  final double min;
  final double max;
  final double warningThreshold;
  final double dangerThreshold;
  final int decimals;
  final double scale;
  final double offset;
  final bool isSigned;
  final String category;

  const BmwSensorDefinition({
    required this.id,
    required this.label,
    required this.did,
    required this.ecu,
    required this.size,
    required this.unit,
    required this.min,
    required this.max,
    required this.warningThreshold,
    required this.dangerThreshold,
    this.decimals = 1,
    this.scale = 1.0,
    this.offset = 0.0,
    this.isSigned = false,
    this.category = 'General',
  });

  double? get warningHigh => warningThreshold;

  bool isWarning(double value) {
    if (warningThreshold > min && value >= warningThreshold) return true;
    if (dangerThreshold < warningThreshold && value <= dangerThreshold) return true;
    return false;
  }

  double convertRaw(int rawValue) {
    int val = rawValue;
    if (isSigned) {
      if (size == 1 && val >= 0x80) {
        val -= 0x100;
      } else if (size == 2 && val >= 0x8000) {
        val -= 0x10000;
      } else if (size == 4 && val >= 0x80000000) {
        val -= 0x100000000;
      }
    }
    return (val * scale) + offset;
  }

  String formatValue(double value) {
    if (id == 'current_gear') {
      final g = value.toInt();
      if (g == 0) return 'P/N';
      if (g == -1 || g >= 254) return 'R';
      return 'D$g';
    }
    if (id == 'knock_detected') {
      return value >= 0.5 ? 'YES' : 'NO';
    }
    return value.toStringAsFixed(decimals);
  }
}

